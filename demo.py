#!/usr/bin/env python3
"""
demo.py — lm-watermark-lab demonstration

Watermarks a sample paragraph with all 3 methods, detects each,
and shows robustness at different noise levels.

Run with:
    python demo.py
"""

import sys
import os
import re

# Make sure local src is on path
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "src"))

from watermark_lab import (
    GreenRedWatermark,
    SemanticWatermark,
    StatisticalWatermark,
    WatermarkDetector,
    RobustnessEvaluator,
)

# ---------------------------------------------------------------------------
# Sample text
# ---------------------------------------------------------------------------
SAMPLE_TEXT = """
Language models have become important tools in modern artificial intelligence research.
They can help researchers find new solutions to common problems and show great results
in many different areas. The development of large language systems has changed the way
we think about natural language processing and its real-world applications.
However, the widespread use of these powerful tools also raises important questions
about safety and the need for clear attribution methods. Researchers therefore often
work to find good ways to make it possible to identify whether a given text was
generated by a language model or by a human author.
""".strip()


def tokenize(text: str):
    """Simple word tokenizer."""
    return re.findall(r"\b\w+\b", text.lower())


def detokenize(tokens):
    return " ".join(tokens)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
SEP = "=" * 68

def print_section(title):
    print(f"\n{SEP}")
    print(f"  {title}")
    print(SEP)

def print_detection(name, result):
    wm = "✅ DETECTED" if result["is_watermarked"] else "❌ not detected"
    print(f"\n  [{name}] {wm}")
    for k, v in result.items():
        if k not in ("is_watermarked", "method", "num_tokens"):
            if isinstance(v, float):
                print(f"    {k}: {v:.4f}")
            else:
                print(f"    {k}: {v}")

def print_robustness_table(name, results):
    print(f"\n  {name} robustness:")
    print(f"    {'Swap rate':>10}  {'Detected':>10}  {'Key stat':>16}")
    for r in results:
        detected = "✅ yes" if r["is_watermarked"] else "❌ no"
        # pick the most informative stat
        if "z_score" in r:
            stat = f"z={r['z_score']:.3f}"
        elif "match_fraction" in r:
            stat = f"match={r['match_fraction']:.3f}"
        elif "chi2" in r:
            stat = f"χ²={r['chi2']:.3f}"
        else:
            stat = ""
        print(f"    {r['swap_rate']:>9.0%}  {detected:>10}  {stat:>16}")


# ---------------------------------------------------------------------------
# Main demo
# ---------------------------------------------------------------------------
def main():
    print_section("lm-watermark-lab — Full Demo")
    print(f"\nSample text ({len(SAMPLE_TEXT.split())} words):")
    print(f"  {SAMPLE_TEXT[:120]}...")

    tokens = tokenize(SAMPLE_TEXT)
    SECRET = "my-secret-watermark-key"

    # -----------------------------------------------------------------------
    # 1. GreenRedWatermark
    # -----------------------------------------------------------------------
    print_section("1. GreenRedWatermark (Kirchenbauer et al. 2023)")
    gr = GreenRedWatermark(secret_key=SECRET, gamma=0.5, delta=2.0)
    gr_tokens = gr.watermark(tokens)
    gr_text = detokenize(gr_tokens)
    print(f"\n  Watermarked (first 120 chars): {gr_text[:120]}...")

    detector_gr = WatermarkDetector(gr)
    gr_result = detector_gr.detect_tokens(gr_tokens)
    print_detection("GreenRedWatermark", gr_result)

    # -----------------------------------------------------------------------
    # 2. SemanticWatermark
    # -----------------------------------------------------------------------
    print_section("2. SemanticWatermark (synonym-based bit encoding)")
    sm = SemanticWatermark(secret_key=SECRET)
    sm_tokens = sm.watermark(tokens)
    sm_text = detokenize(sm_tokens)
    print(f"\n  Watermarked (first 120 chars): {sm_text[:120]}...")

    detector_sm = WatermarkDetector(sm)
    sm_result = detector_sm.detect_tokens(sm_tokens)
    print_detection("SemanticWatermark", sm_result)

    # -----------------------------------------------------------------------
    # 3. StatisticalWatermark
    # -----------------------------------------------------------------------
    print_section("3. StatisticalWatermark (chi-square marker distribution)")
    st = StatisticalWatermark(secret_key=SECRET, period=4, marker_fraction=0.2)
    st_tokens = st.watermark(tokens)
    st_text = detokenize(st_tokens)
    print(f"\n  Watermarked (first 120 chars): {st_text[:120]}...")

    detector_st = WatermarkDetector(st)
    st_result = detector_st.detect_tokens(st_tokens)
    print_detection("StatisticalWatermark", st_result)

    # -----------------------------------------------------------------------
    # 4. Robustness evaluation
    # -----------------------------------------------------------------------
    print_section("4. Robustness Under Paraphrasing Attack")
    print("  Simulating word-swap noise at 0%, 10%, 20%, 30%...")

    evaluator = RobustnessEvaluator(seed=42)
    swap_rates = [0.0, 0.1, 0.2, 0.3]

    gr_robustness = evaluator.evaluate(gr, gr_tokens, swap_rates)
    sm_robustness = evaluator.evaluate(sm, sm_tokens, swap_rates)
    st_robustness = evaluator.evaluate(st, st_tokens, swap_rates)

    print_robustness_table("GreenRedWatermark", gr_robustness)
    print_robustness_table("SemanticWatermark", sm_robustness)
    print_robustness_table("StatisticalWatermark", st_robustness)

    # -----------------------------------------------------------------------
    # 5. Summary comparison
    # -----------------------------------------------------------------------
    print_section("5. Comparison Summary")
    print(f"""
  ┌─────────────────────┬────────────────┬─────────────────┬────────────────────┐
  │ Method              │ Detectability  │ Noise Tolerance │ Key Metric         │
  ├─────────────────────┼────────────────┼─────────────────┼────────────────────┤
  │ GreenRedWatermark   │ z-test (stat.) │ Moderate        │ Green token ratio  │
  │ SemanticWatermark   │ Bit matching   │ Low-Moderate    │ Synonym bit match  │
  │ StatisticalWatermark│ Chi-square     │ Moderate-High   │ Marker set rate    │
  └─────────────────────┴────────────────┴─────────────────┴────────────────────┘

  Notes:
  - GreenRed: Strong statistical grounding, robust to moderate paraphrasing.
  - Semantic: Easily disrupted by synonym-based paraphrasing (by design).
  - Statistical: Periodic pattern is less fragile to random word swaps.
    """)

    print("Demo complete! ✓\n")


if __name__ == "__main__":
    main()
