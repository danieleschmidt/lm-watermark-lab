"""Tests for WatermarkDetector and detect_all."""

import sys
import os
import re
import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from watermark_lab.green_red import GreenRedWatermark
from watermark_lab.semantic import SemanticWatermark
from watermark_lab.statistical import StatisticalWatermark
from watermark_lab.detector import WatermarkDetector, detect_all


SAMPLE = (
    "language models have become important tools in modern artificial intelligence "
    "research they can help researchers find new solutions to common problems and "
    "show great results in many different areas the development of large language "
    "systems has changed the way we think about natural language processing and its "
    "real world applications however the widespread use of these powerful tools also "
    "raises important questions about safety and the need for clear attribution "
    "methods researchers therefore often work to find good ways to make it possible "
    "to identify whether a given text was generated by a language model or by a human"
)


def tokenize(text):
    return re.findall(r"\b\w+\b", text.lower())


class TestWatermarkDetector:

    def test_detect_green_red_from_text(self):
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        tokens = tokenize(SAMPLE)
        wm = gr.watermark(tokens)
        wm_text = " ".join(wm)
        detector = WatermarkDetector(gr)
        result = detector.detect(wm_text)
        assert result["is_watermarked"] is True
        assert result["method"] == "GreenRedWatermark"
        assert result["num_tokens"] == len(tokenize(wm_text))

    def test_detect_semantic_from_text(self):
        sm = SemanticWatermark(secret_key="key")
        tokens = tokenize(SAMPLE)
        wm = sm.watermark(tokens)
        wm_text = " ".join(wm)
        detector = WatermarkDetector(sm)
        result = detector.detect(wm_text)
        assert result["is_watermarked"] is True
        assert result["method"] == "SemanticWatermark"

    def test_detect_statistical_from_text(self):
        st = StatisticalWatermark(secret_key="key", period=4)
        tokens = tokenize(SAMPLE)
        wm = st.watermark(tokens)
        wm_text = " ".join(wm)
        detector = WatermarkDetector(st)
        result = detector.detect(wm_text)
        assert result["is_watermarked"] is True
        assert result["method"] == "StatisticalWatermark"

    def test_detect_tokens_interface(self):
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        tokens = tokenize(SAMPLE)
        wm = gr.watermark(tokens)
        detector = WatermarkDetector(gr)
        result = detector.detect_tokens(wm)
        assert "is_watermarked" in result
        assert result["method"] == "GreenRedWatermark"

    def test_detect_all_returns_all_methods(self):
        tokens = tokenize(SAMPLE)
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        sm = SemanticWatermark(secret_key="key")
        st = StatisticalWatermark(secret_key="key", period=4)

        wm_gr = gr.watermark(tokens)
        wm_text = " ".join(wm_gr)  # use green_red watermarked text for all

        results = detect_all(wm_text, green_red=gr, semantic=sm, statistical=st)
        assert "green_red" in results
        assert "semantic" in results
        assert "statistical" in results

    def test_detect_all_partial(self):
        """detect_all with only some watermarkers provided."""
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        tokens = tokenize(SAMPLE)
        wm = gr.watermark(tokens)
        wm_text = " ".join(wm)
        results = detect_all(wm_text, green_red=gr)
        assert "green_red" in results
        assert "semantic" not in results
        assert "statistical" not in results
