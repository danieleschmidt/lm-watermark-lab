"""Tests for GreenRedWatermark."""

import sys
import os
import re
import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from watermark_lab.green_red import GreenRedWatermark


SAMPLE = (
    "language models have become important tools in modern artificial intelligence "
    "research they can help researchers find new solutions to common problems and "
    "show great results in many different areas the development of large language "
    "systems has changed the way we think about natural language processing and its "
    "real world applications however the widespread use of these powerful tools also "
    "raises important questions about safety and the need for clear attribution "
    "methods researchers therefore often work to find good ways to make it possible "
    "to identify whether a given text was generated by a language model or by a human"
)


def tokenize(text):
    return re.findall(r"\b\w+\b", text.lower())


class TestGreenRedWatermark:

    def test_watermark_returns_same_length(self):
        """Watermarked text should have same number of tokens."""
        gr = GreenRedWatermark(secret_key="test", gamma=0.5)
        tokens = tokenize(SAMPLE)
        wm = gr.watermark(tokens)
        assert len(wm) == len(tokens)

    def test_watermark_detectable(self):
        """Watermarked text should be detected with p-value < 0.05."""
        gr = GreenRedWatermark(secret_key="mykey", gamma=0.5, delta=2.0)
        tokens = tokenize(SAMPLE)
        wm = gr.watermark(tokens)
        result = gr.detect(wm)
        assert result["is_watermarked"] is True
        assert result["p_value"] < 0.05
        assert result["z_score"] > 1.96

    def test_green_fraction_above_gamma(self):
        """Green token fraction should exceed gamma after watermarking."""
        gr = GreenRedWatermark(secret_key="mykey", gamma=0.5)
        tokens = tokenize(SAMPLE)
        wm = gr.watermark(tokens)
        result = gr.detect(wm)
        assert result["green_fraction"] > 0.5

    def test_different_keys_different_results(self):
        """Different keys should produce different watermarks."""
        tokens = tokenize(SAMPLE)
        gr1 = GreenRedWatermark(secret_key="key1", gamma=0.5)
        gr2 = GreenRedWatermark(secret_key="key2", gamma=0.5)
        wm1 = gr1.watermark(tokens)
        wm2 = gr2.watermark(tokens)
        # They should differ in at least some tokens
        assert wm1 != wm2

    def test_unwatermarked_text_not_detected(self):
        """Un-watermarked (plain) text should NOT be consistently detected."""
        gr = GreenRedWatermark(secret_key="mykey", gamma=0.5)
        tokens = tokenize(SAMPLE)
        # Detect without watermarking first
        result = gr.detect(tokens)
        # The green fraction should be closer to 0.5 (not a strong signal)
        assert result["green_fraction"] < 0.65  # not strongly green

    def test_short_text_handled(self):
        """Short token lists should not crash."""
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        result = gr.detect(["hello"])
        assert "is_watermarked" in result

    def test_empty_text(self):
        """Empty token list should return safe defaults."""
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        result = gr.detect([])
        assert result["is_watermarked"] is False

    def test_is_green_deterministic(self):
        """Same prev_token + token should always yield same green decision."""
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        r1 = gr._is_green("hello", "world")
        r2 = gr._is_green("hello", "world")
        assert r1 == r2

    def test_watermark_idempotent_key(self):
        """Same watermarker applied twice should produce same result."""
        gr = GreenRedWatermark(secret_key="stable", gamma=0.5)
        tokens = tokenize(SAMPLE)
        wm1 = gr.watermark(tokens)
        wm2 = gr.watermark(tokens)
        assert wm1 == wm2

    def test_gamma_affects_green_fraction(self):
        """Higher gamma → more tokens in green list → higher green fraction."""
        tokens = tokenize(SAMPLE)
        gr_low = GreenRedWatermark(secret_key="key", gamma=0.25)
        gr_high = GreenRedWatermark(secret_key="key", gamma=0.75)
        wm_low = gr_low.watermark(tokens)
        wm_high = gr_high.watermark(tokens)
        r_low = gr_low.detect(wm_low)
        r_high = gr_high.detect(wm_high)
        assert r_high["green_fraction"] >= r_low["green_fraction"]
