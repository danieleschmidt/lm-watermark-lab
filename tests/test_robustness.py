"""Tests for RobustnessEvaluator."""

import sys
import os
import re
import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from watermark_lab.green_red import GreenRedWatermark
from watermark_lab.semantic import SemanticWatermark
from watermark_lab.statistical import StatisticalWatermark
from watermark_lab.robustness import RobustnessEvaluator


SAMPLE = (
    "language models have become important tools in modern artificial intelligence "
    "research they can help researchers find new solutions to common problems and "
    "show great results in many different areas the development of large language "
    "systems has changed the way we think about natural language processing and its "
    "real world applications however the widespread use of these powerful tools also "
    "raises important questions about safety and the need for clear attribution "
    "methods researchers therefore often work to find good ways to make it possible "
    "to identify whether a given text was generated by a language model or by a human"
)


def tokenize(text):
    return re.findall(r"\b\w+\b", text.lower())


class TestRobustnessEvaluator:

    def test_paraphrase_returns_same_length(self):
        ev = RobustnessEvaluator(seed=42)
        tokens = tokenize(SAMPLE)
        noisy = ev.paraphrase(tokens, swap_rate=0.2)
        assert len(noisy) == len(tokens)

    def test_paraphrase_zero_rate_unchanged(self):
        ev = RobustnessEvaluator(seed=42)
        tokens = tokenize(SAMPLE)
        noisy = ev.paraphrase(tokens, swap_rate=0.0)
        assert noisy == tokens

    def test_paraphrase_changes_tokens_at_nonzero_rate(self):
        ev = RobustnessEvaluator(seed=42)
        tokens = tokenize(SAMPLE)
        noisy = ev.paraphrase(tokens, swap_rate=0.3)
        assert noisy != tokens

    def test_paraphrase_deterministic(self):
        ev = RobustnessEvaluator(seed=99)
        tokens = tokenize(SAMPLE)
        n1 = ev.paraphrase(tokens, swap_rate=0.2)
        n2 = ev.paraphrase(tokens, swap_rate=0.2)
        assert n1 == n2

    def test_evaluate_returns_correct_number_of_records(self):
        ev = RobustnessEvaluator(seed=42)
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        tokens = tokenize(SAMPLE)
        wm = gr.watermark(tokens)
        results = ev.evaluate(gr, wm, swap_rates=[0.0, 0.1, 0.2])
        assert len(results) == 3

    def test_evaluate_result_keys(self):
        ev = RobustnessEvaluator(seed=42)
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        tokens = tokenize(SAMPLE)
        wm = gr.watermark(tokens)
        results = ev.evaluate(gr, wm, swap_rates=[0.0])
        assert "swap_rate" in results[0]
        assert "is_watermarked" in results[0]

    def test_evaluate_0_pct_detects(self):
        """At 0% noise, watermark should always be detected."""
        ev = RobustnessEvaluator(seed=42)
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        tokens = tokenize(SAMPLE)
        wm = gr.watermark(tokens)
        results = ev.evaluate(gr, wm, swap_rates=[0.0])
        assert results[0]["is_watermarked"] is True

    def test_evaluate_all_returns_all_methods(self):
        ev = RobustnessEvaluator(seed=42)
        tokens = tokenize(SAMPLE)
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        sm = SemanticWatermark(secret_key="key")
        st = StatisticalWatermark(secret_key="key", period=4)
        wm_tokens = gr.watermark(tokens)
        results = ev.evaluate_all(
            wm_tokens, green_red=gr, semantic=sm, statistical=st, swap_rates=[0.0, 0.1]
        )
        assert "GreenRedWatermark" in results
        assert "SemanticWatermark" in results
        assert "StatisticalWatermark" in results

    def test_evaluate_all_partial(self):
        ev = RobustnessEvaluator(seed=42)
        tokens = tokenize(SAMPLE)
        gr = GreenRedWatermark(secret_key="key", gamma=0.5)
        wm_tokens = gr.watermark(tokens)
        results = ev.evaluate_all(wm_tokens, green_red=gr, swap_rates=[0.0])
        assert "GreenRedWatermark" in results
        assert "SemanticWatermark" not in results

    def test_higher_noise_lower_detection_signal(self):
        """Higher noise should generally weaken detection signal (not always guaranteed)."""
        ev = RobustnessEvaluator(seed=42)
        st = StatisticalWatermark(secret_key="key", period=4, marker_fraction=0.2)
        tokens = tokenize(SAMPLE)
        wm = st.watermark(tokens)
        results = ev.evaluate(st, wm, swap_rates=[0.0, 0.3])
        chi2_0 = results[0].get("chi2", 0)
        chi2_30 = results[1].get("chi2", 0)
        # chi2 at 30% should be lower or equal to 0% (more noise = weaker signal)
        assert chi2_30 <= chi2_0 * 1.1  # allow 10% tolerance
