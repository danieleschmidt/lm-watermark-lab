"""Tests for SemanticWatermark."""

import sys
import os
import re
import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from watermark_lab.semantic import SemanticWatermark


SAMPLE = (
    "language models have become important tools in modern artificial intelligence "
    "research they can help researchers find new solutions to common problems and "
    "show great results in many different areas the development of large language "
    "systems has changed the way we think about natural language processing and its "
    "real world applications however the widespread use of these powerful tools also "
    "raises important questions about safety and the need for clear attribution "
    "methods researchers therefore often work to find good ways to make it possible "
    "to identify whether a given text was generated by a language model or by a human"
)


def tokenize(text):
    return re.findall(r"\b\w+\b", text.lower())


class TestSemanticWatermark:

    def test_watermark_same_length(self):
        sm = SemanticWatermark(secret_key="test")
        tokens = tokenize(SAMPLE)
        wm = sm.watermark(tokens)
        assert len(wm) == len(tokens)

    def test_watermark_detectable(self):
        sm = SemanticWatermark(secret_key="mykey")
        tokens = tokenize(SAMPLE)
        wm = sm.watermark(tokens)
        result = sm.detect(wm)
        assert result["is_watermarked"] is True
        assert result["match_fraction"] > 0.70

    def test_high_detection_on_clean_watermark(self):
        """A freshly watermarked text should have very high bit match (>90%)."""
        sm = SemanticWatermark(secret_key="mykey")
        tokens = tokenize(SAMPLE)
        wm = sm.watermark(tokens)
        result = sm.detect(wm)
        # Note: detection may be slightly < 100% if synonyms appear naturally in text
        # (e.g., 'widespread' is both a synonym of 'common' and a normal English word)
        assert result["match_fraction"] >= 0.90

    def test_different_keys_different_synonyms(self):
        """Different keys should produce different synonym choices."""
        tokens = tokenize(SAMPLE)
        sm1 = SemanticWatermark(secret_key="key1")
        sm2 = SemanticWatermark(secret_key="key2")
        wm1 = sm1.watermark(tokens)
        wm2 = sm2.watermark(tokens)
        # At least some tokens should differ
        assert wm1 != wm2

    def test_wrong_key_detection_fails(self):
        """Using wrong key for detection should yield low match fraction."""
        tokens = tokenize(SAMPLE)
        sm_encode = SemanticWatermark(secret_key="correct_key")
        sm_wrong = SemanticWatermark(secret_key="wrong_key")
        wm = sm_encode.watermark(tokens)
        result = sm_wrong.detect(wm)
        # match_fraction should be close to 0.5 (chance level), not >0.7
        assert result["match_fraction"] < 0.70

    def test_empty_text(self):
        sm = SemanticWatermark(secret_key="key")
        result = sm.detect([])
        assert result["is_watermarked"] is False
        assert result["total_bits"] == 0

    def test_text_with_no_known_words(self):
        """Text with no synonym-able words should return 0 total bits."""
        sm = SemanticWatermark(secret_key="key")
        tokens = ["xyzzy", "quux", "foobar", "zorp"]
        result = sm.detect(tokens)
        assert result["total_bits"] == 0
        assert result["is_watermarked"] is False

    def test_watermark_idempotent(self):
        """Same watermarker should produce consistent output."""
        sm = SemanticWatermark(secret_key="stable")
        tokens = tokenize(SAMPLE)
        wm1 = sm.watermark(tokens)
        wm2 = sm.watermark(tokens)
        assert wm1 == wm2

    def test_word_bit_deterministic(self):
        """Same key + word always yields same bit."""
        sm = SemanticWatermark(secret_key="key")
        b1 = sm._word_bit("important")
        b2 = sm._word_bit("important")
        assert b1 == b2

    def test_decode_bits_returns_dict(self):
        sm = SemanticWatermark(secret_key="key")
        tokens = tokenize(SAMPLE)
        wm = sm.watermark(tokens)
        decoded = sm.decode_bits(wm)
        assert isinstance(decoded, dict)
        assert len(decoded) > 0

    def test_synonym_replacement_preserves_meaning(self):
        """All replaced words should be recognized synonyms."""
        sm = SemanticWatermark(secret_key="key")
        tokens = tokenize(SAMPLE)
        wm = sm.watermark(tokens)
        for orig, wm_tok in zip(tokens, wm):
            if orig != wm_tok:
                # The replacement should be a synonym of the original
                assert orig in sm.synonyms, f"{orig} not in synonyms"
                assert wm_tok in sm.synonyms[orig] or wm_tok in [
                    s.lower() for s in sm.synonyms[orig]
                ], f"{wm_tok} not a synonym of {orig}"
