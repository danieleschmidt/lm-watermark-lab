"""Tests for StatisticalWatermark."""

import sys
import os
import re
import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from watermark_lab.statistical import StatisticalWatermark


SAMPLE = (
    "language models have become important tools in modern artificial intelligence "
    "research they can help researchers find new solutions to common problems and "
    "show great results in many different areas the development of large language "
    "systems has changed the way we think about natural language processing and its "
    "real world applications however the widespread use of these powerful tools also "
    "raises important questions about safety and the need for clear attribution "
    "methods researchers therefore often work to find good ways to make it possible "
    "to identify whether a given text was generated by a language model or by a human"
)


def tokenize(text):
    return re.findall(r"\b\w+\b", text.lower())


class TestStatisticalWatermark:

    def test_watermark_same_length(self):
        st = StatisticalWatermark(secret_key="test", period=4)
        tokens = tokenize(SAMPLE)
        wm = st.watermark(tokens)
        assert len(wm) == len(tokens)

    def test_watermark_detectable(self):
        st = StatisticalWatermark(secret_key="mykey", period=4, marker_fraction=0.2)
        tokens = tokenize(SAMPLE)
        wm = st.watermark(tokens)
        result = st.detect(wm)
        assert result["is_watermarked"] is True
        assert result["p_value"] < 0.05

    def test_marked_positions_elevated(self):
        """Marker rate at marked positions should be higher than at unmarked."""
        st = StatisticalWatermark(secret_key="mykey", period=4, marker_fraction=0.2)
        tokens = tokenize(SAMPLE)
        wm = st.watermark(tokens)
        result = st.detect(wm)
        assert result["marked_marker_rate"] > result["unmarked_marker_rate"]

    def test_chi2_positive(self):
        st = StatisticalWatermark(secret_key="key", period=4)
        tokens = tokenize(SAMPLE)
        wm = st.watermark(tokens)
        result = st.detect(wm)
        assert result["chi2"] > 0

    def test_different_keys_different_marker_sets(self):
        """Different keys should produce different marker sets."""
        st1 = StatisticalWatermark(secret_key="key1", period=4, marker_fraction=0.2)
        st2 = StatisticalWatermark(secret_key="key2", period=4, marker_fraction=0.2)
        tokens = tokenize(SAMPLE)
        wm1 = st1.watermark(tokens)
        wm2 = st2.watermark(tokens)
        assert wm1 != wm2

    def test_empty_text(self):
        st = StatisticalWatermark(secret_key="key", period=4)
        result = st.detect([])
        assert result["is_watermarked"] is False

    def test_short_text(self):
        st = StatisticalWatermark(secret_key="key", period=4)
        tokens = tokenize("hello world")
        wm = st.watermark(tokens)
        result = st.detect(wm)
        assert "is_watermarked" in result

    def test_is_marked_position(self):
        st = StatisticalWatermark(secret_key="key", period=4)
        assert st.is_marked_position(0) is True
        assert st.is_marked_position(4) is True
        assert st.is_marked_position(8) is True
        assert st.is_marked_position(1) is False
        assert st.is_marked_position(3) is False

    def test_marker_set_respects_fraction(self):
        """Marker set should be approximately marker_fraction * vocab_size."""
        tokens = tokenize(SAMPLE)
        fraction = 0.2
        st = StatisticalWatermark(secret_key="key", period=4, marker_fraction=fraction)
        st._ensure_vocab(tokens)
        vocab_size = len(st._vocab)
        expected = int(vocab_size * fraction)
        assert abs(len(st._marker_set) - expected) <= 1

    def test_watermark_idempotent(self):
        st = StatisticalWatermark(secret_key="stable", period=4)
        tokens = tokenize(SAMPLE)
        wm1 = st.watermark(tokens)
        wm2 = st.watermark(tokens)
        assert wm1 == wm2

    def test_larger_marker_set_detects(self):
        """Both small and large marker fractions should produce detectable watermarks."""
        tokens = tokenize(SAMPLE)
        st_low = StatisticalWatermark(secret_key="key", period=4, marker_fraction=0.1)
        st_high = StatisticalWatermark(secret_key="key", period=4, marker_fraction=0.4)
        wm_low = st_low.watermark(tokens)
        wm_high = st_high.watermark(tokens)
        r_low = st_low.detect(wm_low)
        r_high = st_high.detect(wm_high)
        # Both should be detectable with a sufficiently long text
        assert r_low["is_watermarked"] is True
        assert r_high["is_watermarked"] is True
